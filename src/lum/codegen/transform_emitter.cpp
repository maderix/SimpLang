// Handle management

std::string TransformEmitter::newSSAName(const std::string& hint) {
    std::string name = "%" + hint;
    if (hint.empty()) {
        name = "%v" + std::to_string(ssaCounter_);
    }
    ssaCounter_++;
    return name;
}

void TransformEmitter::registerHandle(const std::string& lumName,
                                       const std::string& ssaName) {
    handles_[lumName] = HandleInfo{ssaName, false, ""};
}

std::string TransformEmitter::getHandle(const std::string& lumName) {
    auto it = handles_.find(lumName);
    if (it == handles_.end()) return "";
    return it->second.ssaName;
}

void TransformEmitter::consumeHandle(const std::string& lumName,
                                      const std::string& consumer) {
    auto it = handles_.find(lumName);
    if (it != handles_.end()) {
        it->second.consumed = true;
        it->second.consumedBy = consumer;
    }
}

void TransformEmitter::rebindHandle(const std::string& lumName,
                                     const std::string& newSSA) {
    auto it = handles_.find(lumName);
    if (it != handles_.end()) {
        it->second.ssaName = newSSA;
        it->second.consumed = false;
        it->second.consumedBy = "";
    }
}

// Output helpers

void TransformEmitter::indent() {
    for (int i = 0; i < indentLevel_; ++i) {
        output_ << "  ";
    }
}

void TransformEmitter::line(const std::string& s) {
    output_ << s << "\n";
}

void TransformEmitter::emit(const std::string& s) {
    output_ << s;
}

